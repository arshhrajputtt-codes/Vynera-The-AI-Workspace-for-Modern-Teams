import enum

from sqlalchemy import Column, DateTime, Enum, Integer, String, Text
from sqlalchemy.sql import func

from app.db.database import Base


class ApprovalStatus(str, enum.Enum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"


class Approval(Base):
    """
    A draft response generated by an AI Employee that a human must
    approve or reject before it's considered final (e.g. before it's sent
    to a customer on an external channel).
    """

    __tablename__ = "approvals"

    id = Column(Integer, primary_key=True, index=True)

    workspace_id = Column(Integer, nullable=False, index=True)
    employee_id = Column(Integer, nullable=False, index=True)
    conversation_id = Column(Integer, nullable=True, index=True)

    prompt = Column(Text, nullable=False)          # what triggered the draft
    draft_content = Column(Text, nullable=False)    # the AI's proposed response

    status = Column(Enum(ApprovalStatus), nullable=False, default=ApprovalStatus.PENDING, index=True)
    requested_by = Column(Integer, nullable=False)
    reviewed_by = Column(Integer, nullable=True)
    review_note = Column(String(500), nullable=True)

    created_at = Column(DateTime(timezone=True), server_default=func.now())
    reviewed_at = Column(DateTime(timezone=True), nullable=True)
